"""Registry of universe-compiler diagnostic codes.

Every ``CompilationMessage.code`` the compiler emits is declared here, grouped
by the pipeline stage that raises it (see ``stages.CompilationStage``). Raise
sites cite registry members, never string literals — the registry is what makes
diagnostics triage-able and greppable in one place.
"""

