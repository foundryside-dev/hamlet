    LEVEL_DRIVE_EXTRINSIC_MISSING = "LEVEL_DRIVE_EXTRINSIC_MISSING"
    LEVEL_DRIVE_INTRINSIC_MISSING = "LEVEL_DRIVE_INTRINSIC_MISSING"

    # --- Stage 5: resolve references ---
    UAC_RES_CASCADE = "UAC-RES-CASCADE"
    UAC_RES_VFS = "UAC-RES-VFS"
    UAC_RES_ITEM = "UAC-RES-ITEM"
    DAC_REF_UNDEFINED_MODIFIER_BAR = "DAC-REF-001"
